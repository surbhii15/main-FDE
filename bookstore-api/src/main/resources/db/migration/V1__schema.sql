-- E-Bookstore schema (PostgreSQL; also runs on H2 in PostgreSQL mode for tests)

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL,
    gift_points   INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label          VARCHAR(50),
    recipient_name VARCHAR(150) NOT NULL,
    line1          VARCHAR(255) NOT NULL,
    line2          VARCHAR(255),
    city           VARCHAR(100) NOT NULL,
    state          VARCHAR(100),
    postal_code    VARCHAR(20)  NOT NULL,
    country        VARCHAR(100) NOT NULL,
    phone          VARCHAR(30),
    is_default     BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_addresses_user ON addresses (user_id);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    slug        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            VARCHAR(50)    NOT NULL UNIQUE,
    title          VARCHAR(255)   NOT NULL,
    author         VARCHAR(150)   NOT NULL,
    isbn           VARCHAR(20)    UNIQUE,
    description    VARCHAR(4000),
    price          NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    stock_quantity INTEGER        NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    delivery_days  INTEGER        NOT NULL DEFAULT 3 CHECK (delivery_days >= 0),
    rating         NUMERIC(2, 1),
    image_url      VARCHAR(500),
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    category_id    BIGINT         NOT NULL REFERENCES categories (id),
    brand_id       BIGINT         NOT NULL REFERENCES brands (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_brand ON products (brand_id);
CREATE INDEX idx_products_author ON products (author);

CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT  NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id BIGINT  NOT NULL REFERENCES products (id),
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    CONSTRAINT uq_cart_product UNIQUE (cart_id, product_id)
);

CREATE TABLE orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number            VARCHAR(30)    NOT NULL UNIQUE,
    user_id                 BIGINT         NOT NULL REFERENCES users (id),
    status                  VARCHAR(20)    NOT NULL,
    subtotal                NUMERIC(12, 2) NOT NULL,
    points_redeemed         INTEGER        NOT NULL DEFAULT 0,
    points_earned           INTEGER        NOT NULL DEFAULT 0,
    discount                NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total                   NUMERIC(12, 2) NOT NULL,
    ship_recipient_name     VARCHAR(150)   NOT NULL,
    ship_line1              VARCHAR(255)   NOT NULL,
    ship_line2              VARCHAR(255),
    ship_city               VARCHAR(100)   NOT NULL,
    ship_state              VARCHAR(100),
    ship_postal_code        VARCHAR(20)    NOT NULL,
    ship_country            VARCHAR(100)   NOT NULL,
    ship_phone              VARCHAR(30),
    estimated_delivery_date DATE           NOT NULL,
    placed_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at            TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_orders_user ON orders (user_id, placed_at);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id BIGINT         NOT NULL REFERENCES products (id),
    title      VARCHAR(255)   NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    line_total NUMERIC(12, 2) NOT NULL
);
CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method          VARCHAR(30)    NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    card_brand      VARCHAR(20),
    card_last4      VARCHAR(4),
    transaction_ref VARCHAR(50),
    failure_reason  VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_payments_order ON payments (order_id);

CREATE TABLE gift_point_transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    order_id    BIGINT      REFERENCES orders (id),
    points      INTEGER     NOT NULL,
    type        VARCHAR(20) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_gpt_user ON gift_point_transactions (user_id, created_at);
